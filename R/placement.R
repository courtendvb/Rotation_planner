#   x: 0 = 左サイドライン 〜 9 = 右サイドライン(ネットに向かって)
#   y: 0 = センターライン 〜 9 = エンドライン

#' 基本ポジション(標準的な立ち位置)
default_placement <- function() {
  data.frame(
    pos = 1:6,
    x = c(7.5, 7.5, 4.5, 1.5, 1.5, 4.5),
    y = c(6.5, 1.5, 1.5, 1.5, 6.5, 6.5)
  )
}

